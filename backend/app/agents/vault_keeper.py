import time
import os
import shutil
import uuid
from typing import Dict, Any, List, Optional
from sqlalchemy.orm import Session

from backend.app.core.config import settings
from backend.app.models.models import Incident, ActionLog, QuarantinedFile, utcnow
from backend.app.utils.security import compute_sha256_file

class VaultKeeper:
    """
    Agent 5: Vault Keeper
    Purpose: Recovery, auditing, incident recording, and damage minimization.
             Guarantees cryptographically verifiable recovery trails and audit logs.
    """
    AGENT_NAME = "Vault Keeper"
    ROLE = "Recovery, Auditing & Incident Management"

    @classmethod
    async def process(
        cls,
        task_id: str,
        scan_id: str,
        file_agent_output: Dict[str, Any],
        risk_agent_output: Dict[str, Any],
        policy_agent_output: Dict[str, Any],
        enforcer_agent_output: Dict[str, Any],
        db: Session
    ) -> Dict[str, Any]:
        start_time = time.time()
        file_data = file_agent_output.get("data", {})
        risk_data = risk_agent_output.get("data", {})
        policy_data = policy_agent_output.get("data", {})
        enforcer_data = enforcer_agent_output.get("data", {})

        scan_type = file_data.get("scan_type", "UNKNOWN")
        input_ref = file_data.get("input_reference", "Target")
        score = risk_data.get("risk_score", 0.0)
        severity = policy_data.get("severity", "LOW")
        decision = policy_data.get("decision", "ALLOW")
        log_incident = policy_data.get("log_incident", False)

        incident_id = None
        recovery_plan = []
        damage_assessment = {
            "confidentiality_impact": "LOW",
            "integrity_impact": "LOW",
            "availability_impact": "LOW",
            "financial_exposure": policy_data.get("financial_risk", "STANDARD")
        }

        # 1. Damage Assessment & Concrete Recovery Plan
        if severity in ("CRITICAL", "HIGH"):
            damage_assessment["confidentiality_impact"] = "HIGH" if "CREDENTIAL" in str(risk_data.get("indicators")) else "MEDIUM"
            damage_assessment["integrity_impact"] = "HIGH" if "ATTACHMENT" in str(risk_data.get("indicators")) else "LOW"
            
            if scan_type == "EMAIL":
                recovery_plan.append("Search mail transport logs for other recipients of this sender.")
                recovery_plan.append("Purge malicious message from company inboxes.")
                if damage_assessment["confidentiality_impact"] == "HIGH":
                    recovery_plan.append("Force immediate password reset and invalidate active sessions for targeted accounts.")
            elif scan_type == "WEBSITE":
                recovery_plan.append("Verify endpoint DNS cache has purged the flagged domain.")
                recovery_plan.append("Submit malicious URL to registrar abuse contact and Google Safe Browsing.")
            elif scan_type == "QR":
                recovery_plan.append("Physically inspect location where QR sticker was found for tampering.")
                recovery_plan.append("Warn users who scanned the code not to approve payment or enter PINs.")
        else:
            recovery_plan.append("No active breach. Continue routine telemetry monitoring.")

        # 2. Record Incident if warranted
        if log_incident or score >= 40.0:
            try:
                incident = Incident(
                    scan_id=scan_id,
                    title=f"Detected {severity} {scan_type} Threat: {input_ref[:60]}",
                    incident_type=f"{scan_type}_FRAUD",
                    severity=severity,
                    status="OPEN",
                    assigned_action=decision,
                    potential_impact=policy_data.get("potential_impact", severity),
                    resolution_notes=f"Auto-generated by Vault Keeper. {len(recovery_plan)} recovery steps recommended."
                )
                db.add(incident)
                db.flush()
                incident_id = incident.id

                # Link quarantined files to scan_id
                q_files = enforcer_data.get("quarantined_files", [])
                for qf_info in q_files:
                    q_record = db.query(QuarantinedFile).filter(QuarantinedFile.id == qf_info.get("quarantine_id")).first()
                    if q_record:
                        q_record.scan_id = scan_id

                # Log enforcer actions into ActionLog
                for act in enforcer_data.get("actions_taken", []):
                    action_log = ActionLog(
                        incident_id=incident_id,
                        agent_name="Enforcer Agent",
                        action_type=decision,
                        action_details=act,
                        performed_by="MultiAgentSystem"
                    )
                    db.add(action_log)

                # Vault Keeper's own audit log
                db.add(ActionLog(
                    incident_id=incident_id,
                    agent_name=cls.AGENT_NAME,
                    action_type="AUDIT_CREATION",
                    action_details=f"Created security incident {incident_id}. Evaluated damage severity: {severity}.",
                    performed_by="VaultKeeper"
                ))
                db.commit()

            except Exception as e:
                db.rollback()
                print(f"VaultKeeper DB Error: {e}")

        execution_time = time.time() - start_time
        summary = (
            f"Vault Keeper finalized audit trail. Incident ID: {incident_id or 'None'}. "
            f"Damage impact: {damage_assessment['confidentiality_impact']}. "
            f"Formulated {len(recovery_plan)} post-incident containment & recovery recommendations."
        )

        return {
            "agent_name": cls.AGENT_NAME,
            "role": cls.ROLE,
            "task_id": task_id,
            "status": "SUCCESS",
            "execution_time_ms": round(execution_time * 1000, 2),
            "summary": summary,
            "data": {
                "incident_id": incident_id,
                "damage_assessment": damage_assessment,
                "recovery_plan": recovery_plan,
                "audit_status": "COMMITTED"
            }
        }

    @classmethod
    def verify_and_restore_file(
        cls,
        quarantine_id: str,
        authorized_by: str,
        reason: str,
        db: Session,
        verify_integrity: bool = True
    ) -> Dict[str, Any]:
        """
        Cryptographically verifies file integrity against the baseline hash,
        then moves the file out of quarantine into the released-files directory.
        """
        q_record = db.query(QuarantinedFile).filter(QuarantinedFile.id == quarantine_id).first()
        if not q_record:
            return {"success": False, "message": "Quarantine record not found"}

        if q_record.status == "RESTORED":
            return {"success": False, "message": "File has already been restored"}

        if not verify_integrity:
            return {
                "success": False,
                "message": "Integrity verification is mandatory before a quarantined file can be released."
            }

        file_path = q_record.file_path
        if not os.path.exists(file_path):
            return {"success": False, "message": "Physical file does not exist on disk"}

        # Stream the file through SHA-256 (safe for large quarantined files).
        current_hash = compute_sha256_file(file_path)

        if current_hash != q_record.file_hash:
            return {
                "success": False,
                "message": f"INTEGRITY CHECK FAILED: Hash mismatch! Expected {q_record.file_hash}, calculated {current_hash}."
            }

        # Move the file to the released directory. The original upload location
        # is not retained, so "restore" means release to a safe, auditable
        # folder rather than trying to guess the original path.
        settings.RESTORE_DIR.mkdir(parents=True, exist_ok=True)
        safe_name = f"restored_{uuid.uuid4().hex[:12]}_{q_record.original_filename}"
        restore_path = settings.RESTORE_DIR / safe_name
        shutil.move(file_path, restore_path)

        q_record.stored_filename = safe_name
        q_record.file_path = str(restore_path)
        q_record.status = "RESTORED"
        q_record.restored_by = authorized_by
        q_record.restored_at = utcnow()

        db.add(ActionLog(
            incident_id=None,
            agent_name=cls.AGENT_NAME,
            action_type="FILE_RESTORED",
            action_details=(
                f"File '{q_record.original_filename}' restored by {authorized_by} to "
                f"{restore_path}. Reason: {reason}. Hash integrity verified."
            ),
            performed_by=authorized_by,
            reversible=False
        ))
        db.commit()

        return {
            "success": True,
            "message": f"File '{q_record.original_filename}' verified and safely restored.",
            "file_hash": current_hash,
            "restored_by": authorized_by,
            "restored_at": q_record.restored_at,
            "restored_path": str(restore_path)
        }
